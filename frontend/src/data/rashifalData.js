const MOON_BASE_SCORE  = { 1:5, 2:6, 3:8, 4:7, 5:9,  6:5, 7:7, 8:4, 9:10, 10:9, 11:10, 12:5 };
const JUPITER_BONUS    = { 1:0, 2:1, 3:0, 4:1, 5:2,  6:0, 7:1, 8:-1,9:2,  10:1, 11:2,  12:-1};
const SATURN_MOD       = { 1:-1,2:0, 3:0, 4:-1,5:-1, 6:1, 7:-1,8:-1,9:0,  10:1, 11:1,  12:0 };
const VENUS_MOD        = { 1:0, 2:0, 3:0, 4:0, 5:1,  6:0, 7:1, 8:0, 9:0,  10:0, 11:0,  12:0 };
const MERCURY_MOD      = { 1:0, 2:0, 3:1, 4:0, 5:1,  6:0, 7:0, 8:0, 9:0,  10:1, 11:0,  12:0 };

function computeScore(mH, jH, sH, vH, meH) {
  const s = (MOON_BASE_SCORE[mH]  || 5)
          + (JUPITER_BONUS[jH]    || 0) * 0.6
          + (SATURN_MOD[sH]       || 0) * 0.4
          + (VENUS_MOD[vH]        || 0) * 0.3
          + (MERCURY_MOD[meH]     || 0) * 0.3;
  return Math.max(3, Math.min(10, Math.round(s)));
}

