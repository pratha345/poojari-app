// ─── Maths helpers ────────────────────────────────────────────────────────────
const PI2  = Math.PI * 2;
const DEG  = Math.PI / 180;
const norm = (d) => ((d % 360) + 360) % 360;

function solveKepler(M, e) {
  let E = M;
  for (let i = 0; i < 12; i++) {
    const dE = (M - E + e * Math.sin(E)) / (1 - e * Math.cos(E));
    E += dE;
    if (Math.abs(dE) < 1e-10) break;
  }
  return E;
}

// ─── Julian Day (UTC) ─────────────────────────────────────────────────────────
function getJD(date) {
  let Y = date.getUTCFullYear(), M = date.getUTCMonth() + 1;
  const D = date.getUTCDate() + date.getUTCHours() / 24 + date.getUTCMinutes() / 1440;
  if (M <= 2) { Y--; M += 12; }
  const A = Math.floor(Y / 100);
  return Math.floor(365.25 * (Y + 4716)) + Math.floor(30.6001 * (M + 1)) + D + 2 - A + Math.floor(A / 4) - 1524.5;
}

// ─── Lahiri ayanamsa (degrees) ────────────────────────────────────────────────
function ayanamsa(T) { return 23.85 + T * 100 * 0.013969; }

// ─── Heliocentric ecliptic rectangular coords from Keplerian elements ─────────
// Elements: [L0,L1, a0,a1, e0,e1, I0,I1, Om0,Om1, om0,om1]
// L = mean longitude, a = semi-major axis, e = eccentricity,
// I = inclination, Om = ascending node, om = longitude of perihelion (ω̃)
function helioRect(el, T) {
  const L   = norm(el[0]  + el[1]  * T);
  const a   = el[2]  + el[3]  * T;
  const e   = el[4]  + el[5]  * T;
  const I   = (el[6]  + el[7]  * T) * DEG;
  const Om  = norm(el[8]  + el[9]  * T) * DEG;
  const omT = norm(el[10] + el[11] * T);          // longitude of perihelion
  const om  = norm(omT - (el[8] + el[9] * T)) * DEG; // argument of perihelion

  const M = norm(L - omT) * DEG;                  // mean anomaly
  const E = solveKepler(M, e);

  const nu = 2 * Math.atan2(Math.sqrt(1 + e) * Math.sin(E / 2), Math.sqrt(1 - e) * Math.cos(E / 2));
  const r  = a * (1 - e * Math.cos(E));

  return {
    x: r * (Math.cos(Om) * Math.cos(nu + om) - Math.sin(Om) * Math.sin(nu + om) * Math.cos(I)),
    y: r * (Math.sin(Om) * Math.cos(nu + om) + Math.cos(Om) * Math.sin(nu + om) * Math.cos(I)),
  };
}

// Geocentric ecliptic longitude = atan2(planet - earth) → sidereal
function geoLon(planetEl, earthEl, T) {
  const p = helioRect(planetEl, T);
  const e = helioRect(earthEl,  T);
  const lon = norm(Math.atan2(p.y - e.y, p.x - e.x) / DEG);
  return norm(lon - ayanamsa(T));
}

