async function importSteps() {
  let updated = 0, skipped = 0;
  for (const [slug, steps] of Object.entries(VIDHI)) {
    const [result] = await pool.query(
      'UPDATE poojas SET steps = ? WHERE slug = ?',
      [JSON.stringify(steps), slug]
    );
    if (result.affectedRows > 0) {
      console.log(`✅ ${slug} — ${steps.length} चरण`);
      updated++;
    } else {
      console.log(`⚠️  ${slug} — सापडले नाही`);
      skipped++;
    }
  }
  const total = Object.values(VIDHI).reduce((a, b) => a + b.length, 0);
  console.log(`\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`);
  console.log(`✅ अपडेट: ${updated} | ⚠️ Missing: ${skipped} | 📿 एकूण चरण: ${total}`);
  process.exit(0);
}

importSteps().catch(e => { console.error('❌', e.message); process.exit(1); });
