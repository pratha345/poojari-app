const seenSlugs = new Set();
for (const a of aartis) {
  if (seenSlugs.has(a.slug)) throw new Error('Duplicate slug in script: ' + a.slug);
  seenSlugs.add(a.slug);
}

(async () => {
  console.log(`\n══════ Inserting ${aartis.length} aartis ══════`);
  let inserted = 0, skipped = 0;

  for (const a of aartis) {
    try {
      const [existing] = await pool.query('SELECT id FROM aartis WHERE slug = ?', [a.slug]);
      if (existing.length) { console.log(`⏭️  SKIP (slug exists): ${a.title}`); skipped++; continue; }

      await pool.query(
        `INSERT INTO aartis (tenant_id, title, slug, deity_category, lyrics, meaning, occasion, source_note, author_name, is_published, views)
         VALUES (1,?,?,?,?,?,?,?,?,1,0)`,
        [a.title, a.slug, a.deity_category, a.lyrics.trim(), a.meaning || null, a.occasion || null, a.source_note || null, a.author_name || null]
      );
      console.log(`✅ INSERTED: ${a.title}`);
      inserted++;
    } catch (err) {
      console.error(`❌ ERROR on "${a.title}":`, err.message);
    }
  }

  console.log(`\n══════ DONE — inserted: ${inserted}, skipped: ${skipped} ══════`);
  process.exit(0);
})().catch(e => { console.error('FATAL:', e); process.exit(1); });
