const excerpt = 'पंचक म्हणजे धनिष्ठा उत्तरार्ध ते रेवती ही साडेचार नक्षत्रे. पंचकात परंपरेने टाळली जाणारी कामे, आणि धर्मसिंधूनुसार पंचकात निधन झाल्यास पाच दर्भ-पुतळ्यांसह दहनाचा विधी, त्यांची नावे, पंचरत्ने, सुतकानंतरचे दान आणि शांती — तसेच इतर नक्षत्रावर मृत्यू पण पंचकात दहन, किंवा उलट, यांचे अपवाद.';

async function main() {
  const [[row]] = await pool.query('SELECT * FROM blog_posts WHERE slug = ?', [SLUG]);
  if (!row) throw new Error(`no post ${SLUG}`);
  const dir = path.join(__dirname, 'backups');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'panchak_blog_before_2026_11_02.json');
  if (!fs.existsSync(file)) fs.writeFileSync(file, JSON.stringify(row, null, 1), 'utf8');
  if (row.content.includes('प्रेतवाहाय')) { console.log('already updated'); return; }
  await pool.query('UPDATE blog_posts SET content = ?, excerpt = ?, read_time = 5 WHERE slug = ?', [content, excerpt, SLUG]);
  console.log(`updated ${SLUG} (id ${row.id}); backup: ${path.relative(process.cwd(), file)}`);
}

main().then(() => process.exit(0)).catch(e => { console.error(e.message); process.exit(1); });
